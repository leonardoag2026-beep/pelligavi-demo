DROP TABLE IF EXISTS historico_status CASCADE;
DROP TABLE IF EXISTS pagamento CASCADE;
DROP TABLE IF EXISTS item_pedido_produto CASCADE;
DROP TABLE IF EXISTS item_pedido CASCADE;
DROP TABLE IF EXISTS pedido CASCADE;
DROP TABLE IF EXISTS endereco CASCADE;
DROP TABLE IF EXISTS preco_produto CASCADE;
DROP TABLE IF EXISTS produto CASCADE;
DROP TABLE IF EXISTS caixa CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;
DROP TABLE IF EXISTS gerente CASCADE;
DROP TABLE IF EXISTS regra_desconto CASCADE;
DROP TABLE IF EXISTS forma_pagamento CASCADE;
DROP TABLE IF EXISTS tipo_pedido CASCADE;
DROP TABLE IF EXISTS canal_origem CASCADE;
DROP TABLE IF EXISTS status_pedido CASCADE;
DROP TABLE IF EXISTS tamanho CASCADE;
DROP TABLE IF EXISTS categoria CASCADE;

-- 01. categoria: categorias do cardapio (pizza, bebida, adicional...)
CREATE TABLE categoria (
    id_categoria  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(50)  NOT NULL,
    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_nome UNIQUE (nome)
);

-- 02. tamanho: tamanhos de pizza
CREATE TABLE tamanho (
    id_tamanho  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(30)  NOT NULL,
    ordem       INTEGER      NOT NULL,
    CONSTRAINT pk_tamanho PRIMARY KEY (id_tamanho),
    CONSTRAINT uq_tamanho_nome UNIQUE (nome)
);

-- 03. status_pedido: dominio de status do pedido
CREATE TABLE status_pedido (
    id_status       INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(30)  NOT NULL,
    ordem           INTEGER      NOT NULL,
    encerra_pedido  BOOLEAN      NOT NULL,
    CONSTRAINT pk_status_pedido PRIMARY KEY (id_status),
    CONSTRAINT uq_status_pedido_nome UNIQUE (nome)
);

-- 04. canal_origem: dominio de canal de origem do pedido
CREATE TABLE canal_origem (
    id_canal  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome      VARCHAR(30)  NOT NULL,
    CONSTRAINT pk_canal_origem PRIMARY KEY (id_canal),
    CONSTRAINT uq_canal_origem_nome UNIQUE (nome)
);

-- 05. tipo_pedido: dominio entrega, retirada ou balcao
CREATE TABLE tipo_pedido (
    id_tipo         INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(30)    NOT NULL,
    exige_endereco  BOOLEAN        NOT NULL,
    taxa_base       NUMERIC(10,2)  NOT NULL,
    CONSTRAINT pk_tipo_pedido PRIMARY KEY (id_tipo),
    CONSTRAINT uq_tipo_pedido_nome UNIQUE (nome),
    CONSTRAINT ck_tipo_pedido_taxa CHECK (taxa_base >= 0)
);

-- 06. forma_pagamento: dominio dinheiro, cartao, PIX
CREATE TABLE forma_pagamento (
    id_forma      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(30)  NOT NULL,
    aceita_troco  BOOLEAN      NOT NULL,
    CONSTRAINT pk_forma_pagamento PRIMARY KEY (id_forma),
    CONSTRAINT uq_forma_pagamento_nome UNIQUE (nome)
);

-- 07. regra_desconto: faixas de desconto por valor do pedido
CREATE TABLE regra_desconto (
    id_regra      INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    valor_minimo  NUMERIC(10,2)  NOT NULL,
    percentual    NUMERIC(5,2)   NOT NULL,
    CONSTRAINT pk_regra_desconto PRIMARY KEY (id_regra),
    CONSTRAINT uq_regra_desconto_valor_minimo UNIQUE (valor_minimo),
    CONSTRAINT ck_regra_desconto_percentual CHECK (percentual BETWEEN 0 AND 100),
    CONSTRAINT ck_regra_desconto_valor_minimo CHECK (valor_minimo >= 0)
);

-- 08. gerente: usuario gerente (login com senha em hash)
CREATE TABLE gerente (
    id_gerente  INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(100)  NOT NULL,
    login       VARCHAR(50)   NOT NULL,
    senha_hash  VARCHAR(255)  NOT NULL,
    CONSTRAINT pk_gerente PRIMARY KEY (id_gerente),
    CONSTRAINT uq_gerente_login UNIQUE (login)
);

-- 09. cliente: clientes (anonimizaveis - LGPD)
CREATE TABLE cliente (
    id_cliente     INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(100)  NOT NULL,
    telefone       VARCHAR(20)   NULL,
    anonimizado    BOOLEAN       NOT NULL DEFAULT FALSE,
    data_cadastro  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente)
);

-- 10. caixa: abertura e fechamento de caixa
CREATE TABLE caixa (
    id_caixa        INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    aberto_em       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valor_inicial   NUMERIC(10,2)  NOT NULL,
    fechado_em      TIMESTAMP      NULL,
    valor_esperado  NUMERIC(10,2)  NULL,
    valor_contado   NUMERIC(10,2)  NULL,
    CONSTRAINT pk_caixa PRIMARY KEY (id_caixa),
    CONSTRAINT ck_caixa_periodo CHECK (fechado_em IS NULL OR fechado_em >= aberto_em),
    CONSTRAINT ck_caixa_valores CHECK (
        valor_inicial >= 0
        AND (valor_esperado IS NULL OR valor_esperado >= 0)
        AND (valor_contado IS NULL OR valor_contado >= 0)
    )
);

-- 11. produto: sabores, bebidas e adicionais
CREATE TABLE produto (
    id_produto    INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_categoria  INTEGER       NOT NULL,
    nome          VARCHAR(100)  NOT NULL,
    descricao     VARCHAR(255)  NULL,
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    disponivel    BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_produto PRIMARY KEY (id_produto),
    CONSTRAINT uq_produto_categoria_nome UNIQUE (id_categoria, nome),
    CONSTRAINT fk_produto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- 12. preco_produto: associativa produto x tamanho: preco por sabor e tamanho
CREATE TABLE preco_produto (
    id_produto  INTEGER        NOT NULL,
    id_tamanho  INTEGER        NOT NULL,
    valor       NUMERIC(10,2)  NOT NULL,
    CONSTRAINT pk_preco_produto PRIMARY KEY (id_produto, id_tamanho),
    CONSTRAINT fk_preco_produto_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_preco_produto_tamanho FOREIGN KEY (id_tamanho) REFERENCES tamanho (id_tamanho)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_preco_produto_valor CHECK (valor >= 0)
);

-- 13. endereco: enderecos do cliente
CREATE TABLE endereco (
    id_endereco  INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_cliente   INTEGER       NOT NULL,
    logradouro   VARCHAR(150)  NOT NULL,
    numero       VARCHAR(10)   NOT NULL,
    complemento  VARCHAR(60)   NULL,
    bairro       VARCHAR(80)   NOT NULL,
    cidade       VARCHAR(80)   NOT NULL,
    cep          VARCHAR(9)    NULL,
    referencia   VARCHAR(150)  NULL,
    apelido      VARCHAR(50)   NULL,
    CONSTRAINT pk_endereco PRIMARY KEY (id_endereco),
    CONSTRAINT fk_endereco_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- 14. pedido: pedido (valores calculados pelo banco no 5.3)
CREATE TABLE pedido (
    id_pedido            INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_cliente           INTEGER        NULL,
    id_status            INTEGER        NOT NULL,
    id_canal             INTEGER        NOT NULL,
    id_tipo              INTEGER        NOT NULL,
    data_hora            TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nome_cliente         VARCHAR(100)   NOT NULL,
    entrega_logradouro   VARCHAR(150)   NULL,
    entrega_numero       VARCHAR(10)    NULL,
    entrega_complemento  VARCHAR(60)    NULL,
    entrega_bairro       VARCHAR(80)    NULL,
    entrega_cidade       VARCHAR(80)    NULL,
    entrega_referencia   VARCHAR(150)   NULL,
    subtotal             NUMERIC(10,2)  NOT NULL,
    taxa_entrega         NUMERIC(10,2)  NOT NULL DEFAULT 0.00,
    desconto             NUMERIC(10,2)  NOT NULL DEFAULT 0.00,
    total                NUMERIC(10,2)  NOT NULL,
    motivo_cancelamento  VARCHAR(255)   NULL,
    CONSTRAINT pk_pedido PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pedido_status_pedido FOREIGN KEY (id_status) REFERENCES status_pedido (id_status)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pedido_canal_origem FOREIGN KEY (id_canal) REFERENCES canal_origem (id_canal)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pedido_tipo_pedido FOREIGN KEY (id_tipo) REFERENCES tipo_pedido (id_tipo)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_pedido_valores CHECK (subtotal >= 0 AND taxa_entrega >= 0 AND desconto >= 0 AND total >= 0),
    CONSTRAINT ck_pedido_total CHECK (total = subtotal + taxa_entrega - desconto)
);

-- 15. item_pedido: itens do pedido
CREATE TABLE item_pedido (
    id_item_pedido  INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_pedido       INTEGER        NOT NULL,
    id_tamanho      INTEGER        NOT NULL,
    quantidade      INTEGER        NOT NULL,
    preco_unitario  NUMERIC(10,2)  NOT NULL,
    observacao      VARCHAR(255)   NULL,
    CONSTRAINT pk_item_pedido PRIMARY KEY (id_item_pedido),
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_item_pedido_tamanho FOREIGN KEY (id_tamanho) REFERENCES tamanho (id_tamanho)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_pedido_preco_unitario CHECK (preco_unitario >= 0)
);

-- 16. item_pedido_produto: associativa item x produto: sabores (meio a meio) e adicionais
CREATE TABLE item_pedido_produto (
    id_item_pedido  INTEGER  NOT NULL,
    id_produto      INTEGER  NOT NULL,
    CONSTRAINT pk_item_pedido_produto PRIMARY KEY (id_item_pedido, id_produto),
    CONSTRAINT fk_item_pedido_produto_item_pedido FOREIGN KEY (id_item_pedido) REFERENCES item_pedido (id_item_pedido)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_item_pedido_produto_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- 17. pagamento: pagamentos do pedido
CREATE TABLE pagamento (
    id_pagamento  INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_pedido     INTEGER        NOT NULL,
    id_forma      INTEGER        NOT NULL,
    valor         NUMERIC(10,2)  NOT NULL,
    data_hora     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    troco_para    NUMERIC(10,2)  NULL,
    CONSTRAINT pk_pagamento PRIMARY KEY (id_pagamento),
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pagamento_forma_pagamento FOREIGN KEY (id_forma) REFERENCES forma_pagamento (id_forma)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0),
    CONSTRAINT ck_pagamento_troco_minimo CHECK (troco_para IS NULL OR troco_para >= valor)
);

-- 18. historico_status: historico de mudancas de status
CREATE TABLE historico_status (
    id_historico  INTEGER    GENERATED BY DEFAULT AS IDENTITY,
    id_pedido     INTEGER    NOT NULL,
    id_status     INTEGER    NOT NULL,
    data_hora     TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_historico_status PRIMARY KEY (id_historico),
    CONSTRAINT fk_historico_status_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_historico_status_status_pedido FOREIGN KEY (id_status) REFERENCES status_pedido (id_status)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

