-- Como cada ingrediente é desenhado na pizza 3D.
-- O motor (pizza3d) tem um RECEITAS embutido; o que estiver aqui tem precedência.
CREATE TABLE IF NOT EXISTS ingrediente_render (
  id_render       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ingrediente  integer NOT NULL UNIQUE REFERENCES ingrediente (id_ingrediente) ON DELETE CASCADE,
  geometria       varchar(20) NOT NULL DEFAULT 'auto',
  params          jsonb NOT NULL DEFAULT '{}'::jsonb,
  modelo_url      varchar(255),
  textura_url     varchar(255),
  atualizado_em   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_render_geometria CHECK (geometria IN ('auto','fio','rodela','desfiado','espalhado','cubo','stl'))
);

COMMENT ON COLUMN ingrediente_render.geometria IS 'fio = traço contínuo; stl = malha enviada pelo modelo_url; auto = usa o RECEITAS do motor';
COMMENT ON COLUMN ingrediente_render.params IS 'raio, cor, passo, faixas, aresta, altura — lidos pelo motor quando existem';

INSERT INTO ingrediente_render (id_ingrediente, geometria, params)
SELECT i.id_ingrediente, 'fio',
       jsonb_build_object('raio', 0.03, 'cor', '#f4ecd8', 'passo', 0.012, 'faixas', 5, 'passadas', 5)
  FROM ingrediente i
 WHERE i.slug = 'catupiry'
   AND NOT EXISTS (SELECT 1 FROM ingrediente_render r WHERE r.id_ingrediente = i.id_ingrediente);
