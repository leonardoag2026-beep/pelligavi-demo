-- tabela: mesma definição do 19_notificacao.sql (IF NOT EXISTS, os dois podem rodar em
-- qualquer ordem sem conflito)
CREATE TABLE IF NOT EXISTS notificacao (
    id_notificacao INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    tipo           VARCHAR(20)  NOT NULL,
    titulo         VARCHAR(120) NOT NULL,
    texto          VARCHAR(240) NULL,
    meta           VARCHAR(40)  NULL,
    lida           BOOLEAN      NOT NULL DEFAULT FALSE,
    criada_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_notificacao PRIMARY KEY (id_notificacao),
    CONSTRAINT ck_notificacao_tipo CHECK (tipo IN ('pedido', 'estoque', 'sistema', 'financeiro'))
);

-- view: agrupa por Hoje / Ontem / Nesta semana / data, para a lista do painel
CREATE OR REPLACE VIEW vw_notificacoes AS
SELECT n.id_notificacao, n.tipo, n.titulo, n.texto, n.meta,
       n.criada_em, n.lida,
       CASE
         WHEN n.criada_em::DATE = CURRENT_DATE                      THEN 'Hoje'
         WHEN n.criada_em::DATE = CURRENT_DATE - INTERVAL '1 day'   THEN 'Ontem'
         WHEN n.criada_em::DATE >= CURRENT_DATE - INTERVAL '7 days' THEN 'Nesta semana'
         ELSE to_char(n.criada_em, 'DD/MM/YYYY')
       END AS grupo
  FROM notificacao n
 ORDER BY n.criada_em DESC;

DROP PROCEDURE IF EXISTS marcar_notificacao_lida(INTEGER);
CREATE OR REPLACE PROCEDURE marcar_notificacao_lida(IN p_id INTEGER)
LANGUAGE plpgsql AS $$
DECLARE
    v_afetadas INTEGER;
BEGIN
    UPDATE notificacao SET lida = TRUE WHERE id_notificacao = p_id;
    GET DIAGNOSTICS v_afetadas = ROW_COUNT;
    IF v_afetadas = 0 THEN
        RAISE EXCEPTION 'Notificação inexistente' USING ERRCODE = '45000';
    END IF;
END $$;

DROP PROCEDURE IF EXISTS notificar_estoque_baixo(INTEGER);
CREATE OR REPLACE PROCEDURE notificar_estoque_baixo(IN p_minimo INTEGER)
LANGUAGE plpgsql AS $$
DECLARE
    v_indisponiveis INTEGER;
BEGIN
    SELECT count(*) INTO v_indisponiveis FROM produto WHERE disponivel = FALSE;

    IF v_indisponiveis >= COALESCE(p_minimo, 1) THEN
        INSERT INTO notificacao (tipo, titulo, texto, meta)
        VALUES ('estoque', 'Estoque baixo',
                'Restam ' || v_indisponiveis || ' itens do cardápio indisponíveis',
                'cardapio');
    END IF;
END $$;
