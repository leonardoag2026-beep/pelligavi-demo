-- 19. notificacao: o que aconteceu no painel. Gravada por gatilho de banco nos
-- eventos de pedido, para nenhum módulo precisar chamar outro.
CREATE TABLE IF NOT EXISTS notificacao (
    id_notificacao INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    tipo           VARCHAR(20)  NOT NULL,
    titulo         VARCHAR(120) NOT NULL,
    texto          VARCHAR(240) NULL,
    meta           VARCHAR(40)  NULL,
    lida           BOOLEAN      NOT NULL DEFAULT FALSE,
    criada_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_notificacao PRIMARY KEY (id_notificacao),
    CONSTRAINT ck_notificacao_tipo CHECK (tipo IN ('pedido', 'estoque', 'sistema', 'financeiro'))
);

CREATE INDEX IF NOT EXISTS ix_notificacao_lida ON notificacao (lida, criada_em DESC);

-- gatilho: cada mudança de status de pedido vira uma notificação
CREATE OR REPLACE FUNCTION fn_notificar_status_pedido() RETURNS TRIGGER AS $$
DECLARE
    numero_pedido VARCHAR(20);
    nome_status   VARCHAR(40);
    tipo_notif    VARCHAR(20);
BEGIN
    -- pedidos criados por procedure podem não ter numero; cai para o id
    SELECT COALESCE(numero::text, id_pedido::text) INTO numero_pedido
      FROM pedido WHERE id_pedido = NEW.id_pedido;
    SELECT nome INTO nome_status FROM status_pedido WHERE id_status = NEW.id_status;

    tipo_notif := CASE WHEN nome_status = 'Entregue' THEN 'financeiro' ELSE 'pedido' END;

    INSERT INTO notificacao (tipo, titulo, texto, meta)
    VALUES (
        tipo_notif,
        'PLG-' || numero_pedido || ' · ' || nome_status,
        COALESCE('Pedido atualizado para ' || lower(nome_status) || '.', 'Pedido atualizado.'),
        'pedido'
    );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tg_notificar_status_pedido ON historico_status;
CREATE TRIGGER tg_notificar_status_pedido
    AFTER INSERT ON historico_status
    FOR EACH ROW EXECUTE FUNCTION fn_notificar_status_pedido();

-- histórico de demonstração: os três pedidos do seed
INSERT INTO notificacao (tipo, titulo, texto, meta, lida, criada_em)
SELECT 'pedido',
       'PLG-' || p.numero || ' · ' || s.nome,
       'Pedido atualizado para ' || lower(s.nome) || '.',
       'pedido',
       p.numero = 1043,
       h.data_hora
  FROM historico_status h
  JOIN pedido p ON p.id_pedido = h.id_pedido
  JOIN status_pedido s ON s.id_status = h.id_status
 WHERE NOT EXISTS (SELECT 1 FROM notificacao n WHERE n.criada_em = h.data_hora);
