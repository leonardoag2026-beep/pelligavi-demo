ALTER TABLE tamanho ADD COLUMN IF NOT EXISTS diametro_cm INTEGER    NULL;
ALTER TABLE tamanho ADD COLUMN IF NOT EXISTS fatias      INTEGER     NULL;
ALTER TABLE tamanho ADD COLUMN IF NOT EXISTS fator       NUMERIC(6,3) NULL;

ALTER TABLE produto ADD COLUMN IF NOT EXISTS slug    VARCHAR(50) NULL;
ALTER TABLE produto ADD COLUMN IF NOT EXISTS detalhe VARCHAR(120) NULL;
ALTER TABLE produto ADD COLUMN IF NOT EXISTS arte    VARCHAR(30) NULL;
ALTER TABLE produto ADD COLUMN IF NOT EXISTS ordem   INTEGER NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS uq_produto_slug   ON produto (slug) WHERE slug IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_tamanho_slug   ON tamanho (slug) WHERE slug IS NOT NULL;

-- ingrediente: o que se compra e o que se coloca na pizza. custo_kg existe para o
-- sistema conferir se o preco da porcao cobre o que foi pago no fornecedor.
CREATE TABLE IF NOT EXISTS ingrediente (
    id_ingrediente  INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    slug            VARCHAR(40)   NOT NULL,
    nome            VARCHAR(80)   NOT NULL,
    classe          VARCHAR(20)   NOT NULL DEFAULT 'outro',
    custo_kg        INTEGER       NOT NULL,
    gramas_porcao   INTEGER       NOT NULL,
    preco_porcao    INTEGER       NOT NULL,
    ativo           BOOLEAN       NOT NULL DEFAULT TRUE,
    ordem           INTEGER       NOT NULL DEFAULT 0,
    criado_em       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_ingrediente PRIMARY KEY (id_ingrediente),
    CONSTRAINT uq_ingrediente_slug UNIQUE (slug),
    CONSTRAINT ck_ingrediente_custo CHECK (custo_kg >= 0),
    CONSTRAINT ck_ingrediente_gramas CHECK (gramas_porcao > 0),
    CONSTRAINT ck_ingrediente_preco CHECK (preco_porcao >= 0)
);

-- sabor_ingrediente: receita. uma linha por ingrediente que compoe o sabor
CREATE TABLE IF NOT EXISTS sabor_ingrediente (
    id_produto      INTEGER NOT NULL,
    id_ingrediente  INTEGER NOT NULL,
    gramas          INTEGER NOT NULL,
    CONSTRAINT pk_sabor_ingrediente PRIMARY KEY (id_produto, id_ingrediente),
    CONSTRAINT fk_sabor_ingrediente_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto) ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_sabor_ingrediente_ingrediente FOREIGN KEY (id_ingrediente)
        REFERENCES ingrediente (id_ingrediente) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_sabor_ingrediente_gramas CHECK (gramas > 0)
);

CREATE INDEX IF NOT EXISTS ix_sabor_ingrediente_produto ON sabor_ingrediente (id_produto);
CREATE INDEX IF NOT EXISTS ix_ingrediente_ativo ON ingrediente (ativo, ordem);
