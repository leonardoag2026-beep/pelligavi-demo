-- 21. reembolso: dinheiro devolvido ao cliente (antes era lista no navegador)
CREATE TABLE IF NOT EXISTS reembolso (
    id_reembolso INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    valor        INTEGER      NOT NULL,
    motivo       VARCHAR(160) NOT NULL DEFAULT 'reembolso manual no painel',
    pedido_ref   VARCHAR(20)  NULL,
    criado_em    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_reembolso PRIMARY KEY (id_reembolso),
    CONSTRAINT ck_reembolso_valor CHECK (valor >= 0)
);

CREATE INDEX IF NOT EXISTS ix_reembolso_data ON reembolso (criado_em DESC);
