-- 08. crm: conversas de atendimento e mensagens
-- Postgres. Uma conversa por canal/cliente; mensagens em ordem cronologica.

CREATE TABLE IF NOT EXISTS conversa (
    id_conversa  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    codigo       VARCHAR(20)  NOT NULL,
    canal        VARCHAR(20)  NOT NULL,
    nome         VARCHAR(80)  NOT NULL,
    pedido       VARCHAR(20)  NULL,
    status       VARCHAR(20)  NOT NULL DEFAULT 'aberta',
    etapa        VARCHAR(30)  NULL,
    nao_lidas    INTEGER      NOT NULL DEFAULT 0,
    aberta_em    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_conversa PRIMARY KEY (id_conversa),
    CONSTRAINT uq_conversa_codigo UNIQUE (codigo),
    CONSTRAINT ck_conversa_status CHECK (status IN ('aberta', 'em_atendimento', 'resolvida')),
    CONSTRAINT ck_conversa_nao_lidas CHECK (nao_lidas >= 0)
);

CREATE TABLE IF NOT EXISTS mensagem (
    id_mensagem  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_conversa  INTEGER      NOT NULL,
    de           VARCHAR(10)  NOT NULL,
    texto        TEXT         NOT NULL,
    tipo         VARCHAR(20)  NOT NULL DEFAULT 'texto',
    anexo        TEXT         NULL,
    enviada_em   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_mensagem PRIMARY KEY (id_mensagem),
    CONSTRAINT fk_mensagem_conversa FOREIGN KEY (id_conversa)
        REFERENCES conversa (id_conversa) ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT ck_mensagem_de CHECK (de IN ('cliente', 'loja')),
    CONSTRAINT ck_mensagem_texto CHECK (length(texto) > 0)
);

CREATE INDEX IF NOT EXISTS ix_mensagem_conversa ON mensagem (id_conversa, enviada_em);
CREATE INDEX IF NOT EXISTS ix_conversa_status ON conversa (status, atualizada_em DESC);
