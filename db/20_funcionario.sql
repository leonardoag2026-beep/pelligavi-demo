-- 20. funcionario: equipe da loja (antes era lista fixa no navegador)
CREATE TABLE IF NOT EXISTS funcionario (
    id_funcionario INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(100) NOT NULL,
    cargo          VARCHAR(40)  NOT NULL DEFAULT 'atendente',
    turno          VARCHAR(30)  NOT NULL DEFAULT '18:00 - 23:30',
    salario        INTEGER      NOT NULL DEFAULT 0,
    telefone       VARCHAR(25)  NULL,
    admissao       DATE         NULL,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_funcionario PRIMARY KEY (id_funcionario),
    CONSTRAINT ck_funcionario_cargo CHECK (cargo IN ('atendente', 'pizzaiolo', 'entregador', 'caixa', 'gerente')),
    CONSTRAINT ck_funcionario_salario CHECK (salario >= 0)
);

CREATE INDEX IF NOT EXISTS ix_funcionario_ativo ON funcionario (ativo, nome);

