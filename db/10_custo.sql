-- 10. custos: contas a pagar e compras de insumo
-- custo_conta guarda o que sai todo mes (aluguel, luz, agua) ou gasto pontual.
-- compra_insumo guarda o que foi pago no fornecedor, para conferir o custo por kg
-- que esta cadastrado no ingrediente.

CREATE TABLE IF NOT EXISTS custo_conta (
    id_custo       INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(80)  NOT NULL,
    categoria      VARCHAR(60)  NOT NULL DEFAULT 'Outros',
    valor          INTEGER      NOT NULL,
    tipo           VARCHAR(15)  NOT NULL DEFAULT 'mensal',
    intervalo_dias INTEGER      NULL,
    icone          VARCHAR(20)  NOT NULL DEFAULT 'outros',
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_custo_conta PRIMARY KEY (id_custo),
    CONSTRAINT ck_custo_conta_valor CHECK (valor >= 0),
    CONSTRAINT ck_custo_conta_tipo CHECK (tipo IN ('mensal', 'imediato', 'periodico')),
    CONSTRAINT ck_custo_conta_intervalo CHECK (
        (tipo = 'periodico' AND intervalo_dias IS NOT NULL AND intervalo_dias > 0)
        OR (tipo <> 'periodico' AND intervalo_dias IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS compra_insumo (
    id_compra      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_ingrediente INTEGER      NOT NULL,
    gramas         INTEGER      NOT NULL,
    valor_total    INTEGER      NOT NULL,
    fornecedor     VARCHAR(80)  NULL,
    comprada_em    DATE         NOT NULL DEFAULT CURRENT_DATE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_compra_insumo PRIMARY KEY (id_compra),
    CONSTRAINT fk_compra_insumo_ingrediente FOREIGN KEY (id_ingrediente)
        REFERENCES ingrediente (id_ingrediente) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_compra_insumo_gramas CHECK (gramas > 0),
    CONSTRAINT ck_compra_insumo_valor CHECK (valor_total >= 0)
);

CREATE INDEX IF NOT EXISTS ix_compra_insumo_ingrediente ON compra_insumo (id_ingrediente, comprada_em DESC);
CREATE INDEX IF NOT EXISTS ix_custo_conta_ativo ON custo_conta (ativo, tipo);
