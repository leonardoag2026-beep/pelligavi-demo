-- 18. cobranca: rascunho de pedido com valor fechado, esperando pagamento
-- É o que o cliente abre no link do PIX antes de o pedido existir.
CREATE TABLE IF NOT EXISTS cobranca (
    id_cobranca  INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    codigo       VARCHAR(20)   NOT NULL,
    valor        INTEGER       NOT NULL,
    subtotal     INTEGER       NOT NULL,
    taxa         INTEGER       NOT NULL DEFAULT 0,
    desconto     INTEGER       NOT NULL DEFAULT 0,
    tipo         VARCHAR(15)   NOT NULL DEFAULT 'entrega',
    metodo       VARCHAR(15)   NOT NULL DEFAULT 'pix',
    status       VARCHAR(20)   NOT NULL DEFAULT 'aguardando',
    nome_cliente VARCHAR(100)  NOT NULL,
    telefone     VARCHAR(25)   NULL,
    endereco     VARCHAR(200)  NULL,
    conta_ref    VARCHAR(40)   NULL,
    cliente_ref  VARCHAR(20)   NULL,
    itens        JSONB         NOT NULL DEFAULT '[]'::jsonb,
    pedido_ref   VARCHAR(20)   NULL,
    criada_em    TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    paga_em      TIMESTAMPTZ   NULL,
    CONSTRAINT pk_cobranca PRIMARY KEY (id_cobranca),
    CONSTRAINT uq_cobranca_codigo UNIQUE (codigo),
    CONSTRAINT ck_cobranca_status CHECK (status IN ('aguardando', 'pago', 'cancelado', 'expirado')),
    CONSTRAINT ck_cobranca_valores CHECK (valor >= 0 AND subtotal >= 0 AND taxa >= 0 AND desconto >= 0)
);

CREATE INDEX IF NOT EXISTS ix_cobranca_status ON cobranca (status, criada_em DESC);
